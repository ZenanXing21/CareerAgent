    async def polish_candidate_intake(
        self, *, draft: CandidateIntakeDraft, facts: IntakeSemanticFacts | None = None
    ) -> IntakePolish:
        prompt_draft = draft.model_copy(update={"photo_asset": None}).model_dump_json()
        prompt_facts = facts.model_dump_json() if facts else "Extract factual keywords first."
        return await self._parse(
            operation="polish_candidate_intake",
            system=(
                "Organize a candidate intake without inventing facts. Normalize hometown "
                "and skill spelling only from supplied values. Rewrite colloquial candidate "
                "language into concise, professional resume language instead of copying it "
                "verbatim. When a self summary exists, return a polished professional_summary; "
                "otherwise keep it null. Return every education source_index exactly once and "
                "professionally organize only its supplied courses, achievements or description. "
                "Classify every experience "
                "as work, internship, campus, competition, research, course, or project. "
                "Respect an explicitly or confidently inferred kind_hint. Campus organizations, "
                "student clubs, school volunteering and on-campus duties are campus; contests are "
                "competition; laboratory or paper work is research; course assignments are course. "
                "Return each source_index exactly once. Generate a concise title and role "
                "when absent, derived only from the experience content. Normalize freely "
                "written date ranges when possible; otherwise preserve their meaning. "
                "Polish descriptions for resume readability but never add employers, duties, "
                "technologies, achievements, metrics, or numbers not present in the source. "
                "Use semantic keywords and factual actions to compose new professional sentences; "
                "do not merely copy the user's wording or prepend '参与' to every sentence. "
                "For work/internship, title is the employer and role is the actual job title; "
                "never duplicate the job title as employer. Preserve all source facts."
            ),
            user=(f"CANDIDATE_INTAKE:\n{prompt_draft}\nSEMANTIC_FACTS:\n{prompt_facts}"),
            schema=IntakePolish,
        )

