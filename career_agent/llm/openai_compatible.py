def _json_object_from_text(text: str) -> object:
    stripped = text.strip()
    fenced = re.fullmatch(r"```(?:json)?\s*(.*?)\s*```", stripped, flags=re.DOTALL)
    if fenced:
        stripped = fenced.group(1).strip()
    try:
        return json.loads(stripped)
    except json.JSONDecodeError:
        start = stripped.find("{")
        end = stripped.rfind("}")
        if start == -1 or end <= start:
            raise
        return json.loads(stripped[start : end + 1])


def _validate_plain_json[T: BaseModel](text: str, schema: type[T]) -> T:
    data = _json_object_from_text(text)
    if schema is _EvidenceMatches:
        if isinstance(data, list):
            data = {"items": data}
        elif isinstance(data, dict) and "items" not in data:
            for alias in ("matches", "evidence_matches"):
                if alias in data:
                    data = {"items": data[alias]}
                    break
    # Strict Pydantic models intentionally reject Python strings for enum/date
    # fields. JSON validation preserves strictness while accepting their valid
    # JSON representations, which is exactly what an LLM response contains.
    return schema.model_validate_json(json.dumps(data, ensure_ascii=False))
