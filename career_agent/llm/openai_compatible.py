class OpenAICompatibleProvider:
    """Strict Pydantic output over an OpenAI-compatible Chat Completions endpoint."""

    def __init__(
        self,
        *,
        api_key: str,
        model: str,
        base_url: str | None = None,
        timeout_seconds: float = 60.0,
    ) -> None:
        if not api_key.strip():
            raise ValueError("api_key must not be empty")
        if not model.strip():
            raise ValueError("model must not be empty")
        self.model = model
        normalized_base_url = (base_url or "").casefold().rstrip("/")
        self._uses_deepseek_json_output = (
            model.casefold().startswith("deepseek-")
            or normalized_base_url == "https://api.deepseek.com"
        )
        self._client = AsyncOpenAI(
            api_key=api_key,
            base_url=base_url,
            timeout=timeout_seconds,
            # Retry transient timeouts, 429s and 5xx responses once. Unsupported
            # response_format errors are 4xx and still fall through immediately
            # to the provider-compatible plain JSON path below.
            max_retries=1,
        )

    @classmethod
    def from_env(cls, *, env_file: str | None = ".env") -> OpenAICompatibleProvider:
        if env_file:
            load_dotenv(env_file, override=False)
        api_key = os.getenv("CAREER_AGENT_LLM_API_KEY", "")
        model = os.getenv("CAREER_AGENT_LLM_MODEL", "")
        base_url = os.getenv("CAREER_AGENT_LLM_BASE_URL") or None
        timeout = float(os.getenv("CAREER_AGENT_LLM_TIMEOUT_SECONDS", "60"))
        if not api_key or not model:
            raise ValueError("CAREER_AGENT_LLM_API_KEY and CAREER_AGENT_LLM_MODEL are required")
        return cls(api_key=api_key, model=model, base_url=base_url, timeout_seconds=timeout)

    async def _parse(
        self,
        *,
        operation: str,
        system: str,
        user: str,
        schema: type[_T],
    ) -> _T:
        # DeepSeek Chat Completions documents JSON Object mode, not the
        # Pydantic/json_schema payload generated by OpenAI SDK's `.parse()`.
        # Its Responses API supports json_schema, but this provider intentionally
        # uses the broadly compatible Chat Completions endpoint.
        if self._uses_deepseek_json_output:
            return await self._parse_plain_json(
                operation=operation,
                system=system,
                user=user,
                schema=schema,
                original_error=None,
                use_json_mode=True,
            )
        try:
            completion = await self._client.chat.completions.parse(
                model=self.model,
                messages=[
                    {"role": "system", "content": system},
                    {"role": "user", "content": user},
                ],
                response_format=schema,
                temperature=0,
            )
        except Exception as exc:
            if not self._should_fallback_to_plain_json(exc):
                # Never include the prompt, provider payload, or key in the workflow error.
                raise LLMProviderError(f"{operation} provider request failed") from exc
            return await self._parse_plain_json(
                operation=operation,
                system=system,
                user=user,
                schema=schema,
                original_error=exc,
                use_json_mode=False,
            )
        message = completion.choices[0].message
        if message.parsed is None:
            raise StructuredOutputError(f"{operation} returned no parsed structured output")
        return message.parsed

    def _should_fallback_to_plain_json(self, exc: Exception) -> bool:
        text = str(exc).casefold()
        return "response_format" in text and (
            "unavailable" in text
            or "unsupported" in text
            or "invalid_request_error" in text
            or "badrequesterror" in text
        )

    async def _parse_plain_json(
        self,
        *,
        operation: str,
        system: str,
        user: str,
        schema: type[_T],
        original_error: Exception | None,
        use_json_mode: bool,
    ) -> _T:
        request_options: dict[str, object] = {}
        if use_json_mode:
            request_options["response_format"] = {"type": "json_object"}
            # V4 Pro defaults to high-effort thinking, which can consume the
            # entire request timeout before emitting the small JSON payloads
            # used by this workflow. DeepSeek officially supports disabling it
            # through extra_body for Chat Completions.
            request_options["extra_body"] = {"thinking": {"type": "disabled"}}
        try:
            completion = await self._client.chat.completions.create(
                model=self.model,
                messages=[
                    {
                        "role": "system",
                        "content": (
                            f"{system}\n\n"
                            "Return only one valid JSON object. Do not wrap it in Markdown. "
                            "The JSON object must satisfy this schema:\n"
                            f"{schema.model_json_schema()}"
                        ),
                    },
                    {"role": "user", "content": user},
                ],
                temperature=0,
                max_tokens=16384,
                **request_options,
            )
        except Exception as exc:
            raise LLMProviderError(
                f"{operation} provider request failed; structured and plain JSON attempts failed"
            ) from exc

        content = completion.choices[0].message.content
        if not content:
            raise StructuredOutputError(
                f"{operation} returned empty plain JSON output"
            ) from original_error
        try:
            return _validate_plain_json(content, schema)
        except (json.JSONDecodeError, ValidationError, ValueError) as first_error:
            return await self._repair_plain_json(
                operation=operation,
                schema=schema,
                invalid_content=content,
                validation_error=first_error,
                use_json_mode=use_json_mode,
            )

    async def _repair_plain_json(
        self,
        *,
        operation: str,
        schema: type[_T],
        invalid_content: str,
        validation_error: Exception,
        use_json_mode: bool,
    ) -> _T:
        """Ask the provider once to correct syntactically or structurally invalid JSON."""
        if isinstance(validation_error, ValidationError):
            error_details = validation_error.json(include_url=False)
        else:
            error_details = str(validation_error)

        request_options: dict[str, object] = {}
        if use_json_mode:
            request_options["response_format"] = {"type": "json_object"}
            request_options["extra_body"] = {"thinking": {"type": "disabled"}}
        try:
            completion = await self._client.chat.completions.create(
                model=self.model,
                messages=[
                    {
                        "role": "system",
                        "content": (
                            "Repair the candidate output so it satisfies the JSON schema exactly. "
                            "Preserve its factual meaning. Return only one valid JSON object, "
                            "without Markdown or commentary.\nSCHEMA:\n"
                            f"{json.dumps(schema.model_json_schema(), ensure_ascii=False)}"
                        ),
                    },
                    {
                        "role": "user",
                        "content": (
                            f"VALIDATION_ERRORS:\n{error_details}\n\n"
                            f"CANDIDATE_OUTPUT:\n{invalid_content}"
                        ),
                    },
                ],
                temperature=0,
                max_tokens=16384,
                **request_options,
            )
        except Exception as exc:
            raise LLMProviderError(
                f"{operation} provider request failed during JSON repair"
            ) from exc

        repaired_content = completion.choices[0].message.content
        if not repaired_content:
            raise StructuredOutputError(
                f"{operation} returned empty output during JSON repair"
            ) from validation_error
        try:
            return _validate_plain_json(repaired_content, schema)
        except (json.JSONDecodeError, ValidationError, ValueError) as exc:
            raise StructuredOutputError(
                f"{operation} returned invalid plain JSON output after one repair attempt"
            ) from exc

    async def parse_resume(self, *, resume_id: str, version: str, raw_text: str) -> Resume:
        return await self._parse(
            operation="parse_resume",
            system=(
                "Extract only facts explicitly present in the resume. Preserve exact source_text "
                "snippets. Never infer missing dates, proficiency, employers, education, "
                "or metrics."
            ),
            user=f"resume_id={resume_id}\nversion={version}\nRESUME:\n{raw_text}",
            schema=Resume,
        )

